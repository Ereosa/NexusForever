using NexusForever.Database.World.Model;
using NexusForever.Game.Abstract.Combat;
using NexusForever.Game.Abstract.Entity.Creature;
using NexusForever.Game.Abstract.Entity;
using NexusForever.Game.Abstract.Entity.Movement;
using NexusForever.Game.Abstract.Entity.Stat;
using NexusForever.Game.Abstract.Spell;
using NexusForever.Game.Abstract.Loot;
using NexusForever.Game.Abstract.Loot.Distribute;
using NexusForever.Network.World.Message.Model;
using NexusForever.Shared.Game;

namespace NexusForever.Game.Entity
{
    /// <summary>
    /// An <see cref="ICreatureEntity"/> is an extension to <see cref="IUnitEntity"/> which contains logic specific to non player controlled combat entities.
    /// </summary>
    public abstract class CreatureEntity : UnitEntity, ICreatureEntity
    {
        #region Dependency Injection

        private readonly ILootDistributor lootDistributor;

        public CreatureEntity(
            IMovementManager movementManager,
            IEntitySummonFactory entitySummonFactory,
            IStatUpdateManager statUpdateManager,
            ISpellFactory spellFactory,
            ILootDistributor lootDistributor)
            : base(movementManager, entitySummonFactory, statUpdateManager, spellFactory)
        {
            this.lootDistributor = lootDistributor;
        }

        #endregion

        /// <summary>
        /// Time before a killed creature is spawned again.
        /// </summary>
        /// <remarks>
        /// Retail values are unknown, the client data has no respawn times.
        /// </remarks>
        protected virtual TimeSpan RespawnDelay => TimeSpan.FromSeconds(90d);

        /// <summary>
        /// Maximum time a corpse stays in the world while it still has loot.
        /// </summary>
        private static readonly TimeSpan MaxCorpseTime = TimeSpan.FromMinutes(3d);

        /// <summary>
        /// Minimum time a corpse stays in the world.
        /// </summary>
        private static readonly TimeSpan MinCorpseTime = TimeSpan.FromSeconds(10d);

        /// <summary>
        /// World database spawn this creature came from, summoned creatures don't have one and don't respawn.
        /// </summary>
        protected EntityModel SpawnModel { get; private set; }

        private UpdateTimer corpseTimer;
        private double corpseAge;

        public override void Initialise(ICreatureInfo creatureInfo, EntityModel model)
        {
            base.Initialise(creatureInfo, model);
            SpawnModel = model;
        }

        /// <summary>
        /// Invoked each world tick with the delta since the previous tick occurred.
        /// </summary>
        public override void Update(double lastTick)
        {
            base.Update(lastTick);

            if (corpseTimer == null)
                return;

            // corpses stay until their loot has been taken
            corpseAge += lastTick;
            corpseTimer.Update(lastTick);
            if (corpseAge < MinCorpseTime.TotalSeconds || (!corpseTimer.HasElapsed && HasRemainingLoot()))
                return;

            corpseTimer = null;
            Map.ScheduleRespawn(CreatureInfo, SpawnModel, RespawnDelay);
            RemoveFromMap();
        }

        protected override void OnDeath(IUnitEntity killer)
        {
            base.OnDeath(killer);

            if (SpawnModel != null && RespawnsOnDeath)
            {
                corpseTimer = new UpdateTimer(MaxCorpseTime);
                corpseAge   = 0d;
            }
        }

        /// <summary>
        /// Returns if this creature is spawned again by <see cref="CreatureEntity"/> after it dies.
        /// </summary>
        protected virtual bool RespawnsOnDeath => true;

        /// <summary>
        /// Returns if any loot generated by this creature is still waiting to be collected.
        /// </summary>
        protected bool HasRemainingLoot()
        {
            foreach (ILootInstance lootInstance in Map.LootManager.GetLootInstances(Guid) ?? [])
                if (lootInstance.GetLootItems().Any())
                    return true;

            return false;
        }

        protected override void GenerateRewards(IUnitEntity killer)
        {
            base.GenerateRewards(killer);

            lootDistributor.Distribute(this);
        }

        /// <summary>
        /// Set target to supplied <see cref="IUnitEntity"/>.
        /// </summary>
        /// <remarks>
        /// A null target will clear the current target.
        /// </remarks>
        public override void SetTarget(IWorldEntity target, uint threat = 0)
        {
            base.SetTarget(target, threat);

            if (target is IPlayer player)
            {
                // plays aggro sound at client, maybe more??
                player.Session.EnqueueMessageEncrypted(new ServerEntityAggroSwitch
                {
                    UnitId   = Guid,
                    TargetId = TargetGuid.Value
                });
            }
        }

        /// <summary>
        /// Invoked when <see cref="ICreatureEntity"/> is targeted by another <see cref="IUnitEntity"/>.
        /// </summary>
        public override void OnTargeted(IUnitEntity source)
        {
            base.OnTargeted(source);

            // client only processes threat list message if the source matches the current target
            if (InCombat && source is IPlayer player)
                ThreatManager.SendThreatList(player.Session);
        }

        /// <summary>
        /// Invoked when a new <see cref="IHostileEntity"/> is added to the threat list.
        /// </summary>
        public override void OnThreatAddTarget(IHostileEntity hostile)
        {
            ThreatManager.BroadcastThreatList();
            base.OnThreatAddTarget(hostile);
        }

        /// <summary>
        /// Invoked when an existing <see cref="IHostileEntity"/> is removed from the threat list.
        /// </summary>
        public override void OnThreatRemoveTarget(IHostileEntity hostile)
        {
            ThreatManager.BroadcastThreatList();
            base.OnThreatRemoveTarget(hostile);
        }

        /// <summary>
        /// Invoked when an existing <see cref="IHostileEntity"/> is update on the threat list.
        /// </summary>
        public override void OnThreatChange(IHostileEntity hostile)
        {
            ThreatManager.BroadcastThreatList();
            base.OnThreatChange(hostile);
        }
    }
}
